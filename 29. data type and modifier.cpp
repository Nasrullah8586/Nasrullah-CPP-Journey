
#include <iostream>
using namespace std;

int main()
{
    // Basic data types
    int age = 22;
    float price = 25.5f;
    double salary = 25000.75;
    char grade = 'A';
    bool isStudent = true;

    // Data type modifiers
    short int a = 10;
    long int b = 100000L;
    unsigned int c = 50;
    long long int d = 1234567890LL;

    cout << "Integer: " << age << endl;
    cout << "Float: " << price << endl;
    cout << "Double: " << salary << endl;
    cout << "Character: " << grade << endl;
    cout << "Boolean: " << isStudent << endl;

    cout << "Short int: " << a << endl;
    cout << "Long int: " << b << endl;
    cout << "Unsigned int: " << c << endl;
    cout << "Long long int: " << d << endl;

    return 0;
}
